// Package preflight is the start-up check of DECISIONS D24: schild,
// schild-lab and schild-relay refuse to start when any configured signing
// key or trust anchor is test material, unless the test lab override
// SCHILD_ALLOW_TEST_KEYS=1 is set. Release builds (-tags release) ignore the
// override: they refuse test material whatever the environment says.
//
// Test material is
//
//   - a key whose public key is one of contracts/testkeys (keys.IsTestKey,
//     including the test lab key of lab-d listed since v0.2),
//   - a key id starting with "test" (covers "test-…" and "testlab-…"),
//   - the test lab CA among the trusted CAs (SCHILD_TEST_CA, SSL_CERT_FILE,
//     SSL_CERT_DIR and the system bundle files), recognised by the embedded
//     SHA-256 fingerprint of testlab/compose/secrets/ca.pem and by its
//     subject marker "(TEST ONLY)", which also catches a regenerated test CA,
//   - a serving certificate issued by that test CA.
//
// The components collect findings into a Report and call Enforce before
// they open any listener. "preflight" sub-commands print the same report
// without starting (runbook stage 3, section 4.4).
package preflight

import (
	"crypto/ed25519"
	"crypto/sha256"
	"crypto/x509"
	"encoding/hex"
	"encoding/pem"
	"fmt"
	"io"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/deutschland-schild/schild/contract/keys"
)

// OverrideEnv is the explicit test lab override. Only the value "1" counts,
// and only in builds without -tags release.
const OverrideEnv = "SCHILD_ALLOW_TEST_KEYS"

// TestKeyIDPrefix: no production key id may start with it (D24). Wider than
// keys.TestKeyIDPrefix ("test-") on purpose.
const TestKeyIDPrefix = "test"

// TestCAFingerprints are SHA-256 fingerprints (DER, lower-case hex) of test
// lab CAs. The first is testlab/compose/secrets/ca.pem as generated for
// stage 2 (subject "Schild test CA (TEST ONLY)"). The CA is regenerated by
// `FORCE=1 make testlab-secrets`; TestCASubjectMarker catches those.
var TestCAFingerprints = []string{
	"9d8acd9994ae64569e36d8e21e0dfd620e774553f05636a37513d67f04680a13",
}

// TestCASubjectMarker is part of the subject common name of every test CA
// that `schild-lab dev-certs` creates.
const TestCASubjectMarker = "(TEST ONLY)"

// systemBundleFiles and systemBundleDirs mirror the locations Go's
// crypto/x509 reads on Linux when SSL_CERT_FILE / SSL_CERT_DIR are not set.
var (
	systemBundleFiles = []string{
		"/etc/ssl/certs/ca-certificates.crt",
		"/etc/pki/tls/certs/ca-bundle.crt",
		"/etc/ssl/ca-bundle.pem",
		"/etc/pki/tls/cacert.pem",
		"/etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem",
		"/etc/ssl/cert.pem",
	}
	systemBundleDirs = []string{"/etc/ssl/certs", "/etc/pki/tls/certs"}
)

// Kinds of findings.
const (
	KindTestKey     = "test_key"       // public key from contracts/testkeys
	KindTestKeyID   = "test_keyid"     // key id starts with "test"
	KindTestCA      = "test_ca"        // test lab CA among trusted CAs
	KindTestCAIssue = "test_ca_issued" // serving certificate issued by the test CA
)

// Finding is one piece of test material.
type Finding struct {
	Kind   string `json:"kind"`
	Where  string `json:"where"` // config path or environment variable
	Detail string `json:"detail"`
}

func (f Finding) String() string { return f.Where + ": " + f.Detail }

// Report collects the findings of one component.
type Report struct {
	Component string
	Findings  []Finding
	Notes     []string // checked items and things that could not be checked
	// Override is true when SCHILD_ALLOW_TEST_KEYS=1 was set in a build
	// without -tags release.
	Override bool
	// Env reads environment variables (os.Getenv by default; tests replace it).
	Env func(string) string
	// SystemFiles and SystemDirs replace the system bundle locations (tests).
	SystemFiles, SystemDirs []string
}

// New starts a report for a component and reads the override.
func New(component string) *Report {
	return NewWithEnv(component, os.Getenv)
}

// NewWithEnv is New with a custom environment (tests).
func NewWithEnv(component string, env func(string) string) *Report {
	r := &Report{Component: component, Env: env}
	r.Override = overrideSet(env)
	return r
}

// overrideSet reads OverrideEnv. Release builds never honour it: the
// override exists for the local test lab, which never runs release builds.
func overrideSet(env func(string) string) bool {
	return !keys.Release && env(OverrideEnv) == "1"
}

func (r *Report) add(kind, where, format string, a ...any) {
	r.Findings = append(r.Findings, Finding{Kind: kind, Where: where, Detail: fmt.Sprintf(format, a...)})
}

func (r *Report) note(format string, a ...any) { r.Notes = append(r.Notes, fmt.Sprintf(format, a...)) }

// IsTestKeyID reports whether a key id is refused by its prefix.
func IsTestKeyID(keyid string) bool {
	return strings.HasPrefix(strings.ToLower(strings.TrimSpace(keyid)), TestKeyIDPrefix)
}

// KeyID checks a key id alone.
func (r *Report) KeyID(where, keyid string) {
	if IsTestKeyID(keyid) {
		r.add(KindTestKeyID, where, "key id %q starts with %q (test key ids are refused)", keyid, TestKeyIDPrefix)
	}
}

// Key checks a key id and its public key.
func (r *Report) Key(where, keyid string, pub ed25519.PublicKey) {
	r.KeyID(where, keyid)
	if len(pub) == ed25519.PublicKeySize && keys.IsTestKey("", pub) {
		r.add(KindTestKey, where, "key %q is a public TEST ONLY key from contracts/testkeys", keyid)
	}
}

// PublicKey checks a key id and a public key string ("ed25519:<b64>").
// Unparsable keys are left to the config validation.
func (r *Report) PublicKey(where, keyid, public string) {
	pub, err := keys.ParsePublicKey(public)
	if err != nil {
		r.KeyID(where, keyid)
		return
	}
	r.Key(where, keyid, pub)
}

// PrivateKeyFile checks a key id and the private key in a seed file. A file
// that cannot be read is noted (the component reports it on its own).
func (r *Report) PrivateKeyFile(where, keyid, path string) {
	b, err := os.ReadFile(path)
	if err != nil {
		r.KeyID(where, keyid)
		r.note("%s: key file %s not readable, only the key id was checked (%v)", where, path, err)
		return
	}
	priv, err := keys.ParseSeedFile(b)
	if err != nil {
		r.KeyID(where, keyid)
		r.note("%s: key file %s not parsable, only the key id was checked", where, path)
		return
	}
	r.Key(where, keyid, priv.Public().(ed25519.PublicKey))
	// keygen writes mode 0600. A wider mode is noted, not refused: mounted
	// secrets (containers) often come with other modes the operator chose.
	if fi, err := os.Stat(path); err == nil && fi.Mode().Perm()&0o077 != 0 {
		r.note("%s: key file %s is accessible to other users (mode %04o): chmod 600", where, path, fi.Mode().Perm())
	}
}

// Fingerprint returns the SHA-256 fingerprint of a DER certificate.
func Fingerprint(der []byte) string {
	h := sha256.Sum256(der)
	return hex.EncodeToString(h[:])
}

// IsTestCA reports whether a certificate is a test lab CA.
func IsTestCA(c *x509.Certificate) bool {
	fp := Fingerprint(c.Raw)
	for _, t := range TestCAFingerprints {
		if fp == t {
			return true
		}
	}
	return strings.Contains(c.Subject.CommonName, TestCASubjectMarker)
}

func parseCerts(b []byte) []*x509.Certificate {
	var out []*x509.Certificate
	for {
		var blk *pem.Block
		blk, b = pem.Decode(b)
		if blk == nil {
			return out
		}
		if blk.Type != "CERTIFICATE" {
			continue
		}
		if c, err := x509.ParseCertificate(blk.Bytes); err == nil {
			out = append(out, c)
		}
	}
}

// CAFile checks a PEM bundle of trusted CAs. Returns false when the file
// could not be read.
func (r *Report) CAFile(where, path string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		r.note("%s: %s not readable (%v)", where, path, err)
		return false
	}
	for _, c := range parseCerts(b) {
		if IsTestCA(c) {
			r.add(KindTestCA, where, "trusted CA %q (sha256 %s) in %s is the test lab CA", c.Subject.CommonName, Fingerprint(c.Raw), path)
		}
	}
	return true
}

func (r *Report) caDir(where, dir string) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	n := 0
	for _, e := range ents {
		if n >= 4096 {
			r.note("%s: stopped after 4096 files in %s", where, dir)
			return
		}
		p := filepath.Join(dir, e.Name())
		fi, err := os.Stat(p) // follows the hash symlinks of c_rehash
		if err != nil || !fi.Mode().IsRegular() || fi.Size() > 4<<20 {
			continue
		}
		n++
		r.CAFile(where, p)
	}
}

// TrustAnchors checks every CA source the component trusts: SCHILD_TEST_CA
// and the system roots (SSL_CERT_FILE, SSL_CERT_DIR, else the bundle files
// and directories Go reads on Linux).
func (r *Report) TrustAnchors() {
	if p := r.Env("SCHILD_TEST_CA"); p != "" {
		r.CAFile("SCHILD_TEST_CA", p)
	}
	files, dirs := r.SystemFiles, r.SystemDirs
	if files == nil {
		files = systemBundleFiles
	}
	if dirs == nil {
		dirs = systemBundleDirs
	}
	if p := r.Env("SSL_CERT_FILE"); p != "" {
		r.CAFile("SSL_CERT_FILE", p)
	} else {
		for _, f := range files {
			if _, err := os.Stat(f); err == nil { // a missing default bundle is normal
				r.CAFile("system roots", f)
				break
			}
		}
	}
	if d := r.Env("SSL_CERT_DIR"); d != "" {
		for _, dd := range filepath.SplitList(d) {
			r.caDir("SSL_CERT_DIR", dd)
		}
	} else {
		for _, dd := range dirs {
			r.caDir("system roots", dd)
		}
	}
}

// ServingCert checks that a TLS certificate this component serves is not
// issued by (or is) the test lab CA. Missing files are noted.
func (r *Report) ServingCert(where, path string) {
	if path == "" {
		return
	}
	b, err := os.ReadFile(path)
	if err != nil {
		r.note("%s: %s not readable (%v)", where, path, err)
		return
	}
	for _, c := range parseCerts(b) {
		if IsTestCA(c) || strings.Contains(c.Issuer.CommonName, TestCASubjectMarker) {
			r.add(KindTestCAIssue, where, "certificate %q in %s is issued by the test lab CA", c.Subject.CommonName, path)
		}
	}
}

// OK reports whether no test material was found.
func (r *Report) OK() bool { return len(r.Findings) == 0 }

// Err returns nil when the component may start: no findings, or the
// override is set.
func (r *Report) Err() error {
	if r.OK() || r.Override {
		return nil
	}
	return fmt.Errorf("preflight: refusing to start %s: %d test key or test CA finding(s): %s (set %s=1 only in the local test lab)",
		r.Component, len(r.Findings), r.summary(), OverrideEnv)
}

func (r *Report) summary() string {
	var s []string
	for _, f := range r.Findings {
		s = append(s, f.String())
	}
	sort.Strings(s)
	return strings.Join(s, "; ")
}

// Enforce logs the result and returns Err. With the override and findings it
// logs a warning and lets the component start.
func (r *Report) Enforce(log *slog.Logger) error {
	switch {
	case r.OK():
		log.Info("preflight passed: no test keys, no test key ids, no test lab CA")
		return nil
	case r.Override:
		log.Warn("preflight: TEST LAB OVERRIDE "+OverrideEnv+"=1, starting with test keys or test CA (never in production)",
			"findings", len(r.Findings), "details", r.summary())
		return nil
	}
	err := r.Err()
	log.Error(err.Error(), "findings", len(r.Findings))
	return err
}

// Print writes a human-readable result. The caller exits with a non-zero
// status when Err is not nil.
func (r *Report) Print(w io.Writer) {
	fmt.Fprintf(w, "%s preflight\n", r.Component)
	for _, f := range r.Findings {
		fmt.Fprintf(w, "  REFUSE  [%s] %s\n", f.Kind, f)
	}
	for _, n := range r.Notes {
		fmt.Fprintf(w, "  note    %s\n", n)
	}
	switch {
	case r.OK():
		fmt.Fprintln(w, "result: PASS (no test keys, no key ids starting with \"test\", no test lab CA)")
	case r.Override:
		fmt.Fprintf(w, "result: WOULD REFUSE, but %s=1 is set (test lab override): the component starts anyway\n", OverrideEnv)
	default:
		fmt.Fprintf(w, "result: REFUSE (%d finding(s)); the component does not start\n", len(r.Findings))
	}
}
