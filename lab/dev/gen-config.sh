#!/usr/bin/env bash
# Writes a TEST ONLY three-lab setup (lab-a, lab-b, lab-c of three operators)
# into DIR: lab.yaml, keys/lab.key and tls/ per lab, plus ca.pem.
#
#   lab/dev/gen-config.sh DIR native   # all on localhost, distinct ports
#   lab/dev/gen-config.sh DIR docker   # container host names, default ports
#
# Needs: go (for contract/cmd/testkeyfile) and a schild-lab binary in $SCHILD_LAB_BIN.
set -euo pipefail
dir=$1 mode=${2:-docker}
root=$(cd "$(dirname "$0")/../.." && pwd)  # repository root
bin=${SCHILD_LAB_BIN:?set SCHILD_LAB_BIN to a schild-lab binary}
mkdir -p "$dir"
"$bin" dev-certs -out "$dir/certs" -hosts lab-a,lab-b,lab-c,relay-1 >/dev/null
cp "$dir/certs/ca.pem" "$dir/ca.pem"
pub() { (cd "$root/contract" && go run ./cmd/testkeyfile -name "$1" -public | cut -d' ' -f2); }
portof() { case $1 in lab-a) echo 1;; lab-b) echo 2;; lab-c) echo 3;; esac; }
opof() { echo "op-test-${1#lab-}"; }
site_a=$(pub site-a) site_b=$(pub site-b) site_c=$(pub site-c)
for lab in lab-a lab-b lab-c; do
  d="$dir/$lab"; mkdir -p "$d/keys" "$d/tls"
  (cd "$root/contract" && go run ./cmd/testkeyfile -name "$lab") > "$d/keys/lab.key"
  chmod 0644 "$d/keys/lab.key"   # TEST ONLY key, read by the container's nonroot user
  cp "$dir/certs/$lab/cert.pem" "$dir/certs/$lab/key.pem" "$d/tls/"
  if [ "$mode" = native ]; then
    n=$(portof "$lab")
    listen="{ ingest: \"127.0.0.1:${n}7443\", feed: \"127.0.0.1:${n}7444\", dashboard: \"127.0.0.1:${n}8789\", metrics: \"127.0.0.1:${n}9102\" }"
    etc="$d"; storage="$d/data"
  else
    listen='{ ingest: "0.0.0.0:7443", feed: "0.0.0.0:7444", dashboard: "0.0.0.0:8789", metrics: "0.0.0.0:9102" }'
    etc=/etc/schild-lab; storage=/var/lib/schild-lab
  fi
  {
    echo "# TEST ONLY: test keys, test CA. Generated by lab/dev/gen-config.sh."
    echo "config_version: 0"
    echo "profile: test"
    echo "identity: { operator: $(opof "$lab"), lab: $lab }"
    echo "listen: $listen"
    echo "tls: { cert_file: $etc/tls/cert.pem, key_file: $etc/tls/key.pem }"
    echo "channel: schild-main"
    echo "keys:"
    echo "  - { keyid: test-$lab, private_key_file: $etc/keys/lab.key, purposes: [ack, rules, checkpoint] }"
    echo "issuers: [ { id: issuer-test-1 }, { id: issuer-test-2 } ]"
    echo "clients:"
    echo "  - { keyid: test-site-a, public_key: \"$site_a\", issuer: issuer-test-1 }"
    echo "  - { keyid: test-site-b, public_key: \"$site_b\", issuer: issuer-test-1 }"
    echo "  - { keyid: test-site-c, public_key: \"$site_c\", issuer: issuer-test-2 }"
    echo "publish: { checkpoint_interval_s: 5, checkpoint_ttl_s: 60 }"
    echo "storage: { path: $storage }"
    echo "peers:"
    for p in lab-a lab-b lab-c; do
      [ "$p" = "$lab" ] && continue
      if [ "$mode" = native ]; then ep="https://localhost:$(portof "$p")7444"; else ep="https://$p:7444"; fi
      echo "  - lab: $p"
      echo "    operator: $(opof "$p")"
      echo "    endpoint: \"$ep\""
      echo "    keys: [ { keyid: test-$p, public_key: \"$(pub "$p")\", purposes: [ack, rules, checkpoint] } ]"
    done
  } > "$d/lab.yaml"
  if [ "$mode" = native ]; then SCHILD_LAB_CONFIG="$d/lab.yaml" "$bin" check-config >/dev/null; fi
done
echo "three-lab TEST ONLY setup written to $dir ($mode)"
