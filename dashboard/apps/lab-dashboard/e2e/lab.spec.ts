test('command palette and shortcut help', async ({ page }) => {
  await login(page)
  const palette = page.getByRole('dialog', { name: 'Befehle' })
  // The global listener attaches right after the first paint; retry the chord until the palette shows.
  await expect(async () => {
    if (!(await palette.isVisible())) await page.keyboard.press('ControlOrMeta+k')
    await expect(palette).toBeVisible({ timeout: 500 })
  }).toPass({ timeout: 5000 })
  await page.keyboard.type('Öffentliches')
  const option = palette.getByRole('option', { name: 'Öffentliches Log' })
  await expect(option).toBeVisible()
  await expect(palette.getByRole('option')).toHaveCount(1)
  if ((await option.getAttribute('data-highlighted')) === null) await page.keyboard.press('ArrowDown')
  await expect(option).toHaveAttribute('data-highlighted', '')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { level: 1, name: 'Öffentliches Log' })).toBeVisible()
  await page.keyboard.press('g')
  await page.keyboard.press('v')
  await expect(page.getByRole('heading', { level: 1, name: 'Vorschläge' })).toBeVisible()
  await page.keyboard.press('Shift+?')
  await expect(page.getByRole('dialog', { name: 'Tastenkürzel' })).toBeVisible()
})

