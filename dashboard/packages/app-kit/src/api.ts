import type { Client, ClientOptions, Middleware } from 'openapi-fetch'
import createClient from 'openapi-fetch'

/** Error thrown for non-2xx responses; carries the problem body if any. */
export class ApiError extends Error {
  readonly status: number
  readonly body: unknown
  constructor(status: number, body: unknown, message?: string) {
    super(message ?? problemTitle(body) ?? `HTTP ${status}`)
    this.name = 'ApiError'
    this.status = status
    this.body = body
  }
}

function problemTitle(body: unknown): string | undefined {
  if (body && typeof body === 'object') {
    const b = body as Record<string, unknown>
    if (typeof b.title === 'string') return b.title
    if (typeof b.message === 'string') return b.message
    if (typeof b.error === 'string') return b.error
  }
  return undefined
}

/**
 * Pluggable dashboard auth. The dashboard runs behind login or on localhost (concept 24);
 * the concrete scheme is decided by the backend. Returns headers to add, or nothing.
 */
export interface AuthProvider {
  headers: () => Record<string, string> | Promise<Record<string, string>>
  /** Called on 401 (e.g. redirect to login). */
  onUnauthorized?: () => void
}

/**
 * Base URL of the app's backend: the directory of the current document.
 * Works at root and under any sub-path (go:embed), with hash routing.
 * Override with VITE_API_BASE for development against a remote backend.
 */
export function defaultBaseUrl(prefix = ''): string {
  const env = import.meta.env.VITE_API_BASE as string | undefined
  if (env) return env.replace(/\/$/, '') + prefix
  if (typeof window === 'undefined') return prefix
  const dir = new URL('.', window.location.href)
  dir.hash = ''
  dir.search = ''
  return dir.href.replace(/\/$/, '') + prefix
}

export interface CreateApiOptions extends Omit<ClientOptions, 'baseUrl'> {
  /** Path prefix from the OpenAPI `servers[0].url` (e.g. "/api/v0"). */
  prefix?: string
  baseUrl?: string
  auth?: AuthProvider
}

/** Typed API client for an OpenAPI `paths` type generated by `pnpm gen:api`. */
export function createApi<Paths extends {}>(options: CreateApiOptions = {}): Client<Paths> {
  const { prefix = '', baseUrl, auth, ...rest } = options
  const client = createClient<Paths>({ baseUrl: baseUrl ?? defaultBaseUrl(prefix), ...rest })
  const mw: Middleware = {
    async onRequest({ request }) {
      if (auth) {
        for (const [k, v] of Object.entries(await auth.headers())) request.headers.set(k, v)
      }
      request.headers.set('Accept', 'application/json')
      return request
    },
    onResponse({ response }) {
      if (response.status === 401) auth?.onUnauthorized?.()
      return response
    },
  }
  client.use(mw)
  return client
}

/** Turn an openapi-fetch result into data or a thrown ApiError (for vue-query). */
export async function unwrap<T>(result: Promise<{ data?: T, error?: unknown, response: Response }>): Promise<T> {
  const { data, error, response } = await result
  if (!response.ok || error !== undefined) throw new ApiError(response.status, error)
  return data as T
}
