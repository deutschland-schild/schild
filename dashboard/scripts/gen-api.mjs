#!/usr/bin/env node
// Generate typed API clients for the dashboards from contracts/api/*.{yaml,yml,json}.
//   apps/<app>/src/api/generated/schema.ts      openapi-typescript `paths`/`components`
//   apps/<app>/src/api/generated/operations.ts  the API prefix of the spec's server URL
// The spec for an app is the file in contracts/api whose name contains the app key ("client" or "lab").
// Without a spec, a placeholder is written so the apps still type-check.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { parse } from 'yaml'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const apiDir = process.env.SCHILD_API_DIR ? resolve(process.env.SCHILD_API_DIR) : resolve(root, '../contracts/api')
const apps = [
  { key: 'client', dir: 'apps/client-dashboard' },
  { key: 'lab', dir: 'apps/lab-dashboard' },
]
const header = src => `// Code generated by scripts/gen-api.mjs from ${src}. DO NOT EDIT.\n// Regenerate with: pnpm gen:api\n/* eslint-disable */\n`

function findSpec(key) {
  if (!existsSync(apiDir)) return undefined
  const files = readdirSync(apiDir).filter(f => /\.(ya?ml|json)$/i.test(f) && f.toLowerCase().includes(key))
  files.sort((a, b) => a.length - b.length)
  return files[0] ? join(apiDir, files[0]) : undefined
}

function serverPrefix(doc) {
  const url = doc.servers?.[0]?.url
  if (!url) return ''
  try {
    return new URL(url, 'http://x').pathname.replace(/\/$/, '')
  }
  catch {
    return ''
  }
}

let failed = false
for (const app of apps) {
  const outDir = resolve(root, app.dir, 'src/api/generated')
  mkdirSync(outDir, { recursive: true })
  const spec = findSpec(app.key)
  if (!spec) {
    console.warn(`[gen:api] no OpenAPI file for "${app.key}" in ${apiDir}; writing placeholder`)
    writeFileSync(join(outDir, 'schema.ts'), `${header('(no spec yet)')}export interface paths {}\nexport interface components { schemas: Record<string, never> }\nexport type operations = Record<string, never>\n`)
    writeFileSync(join(outDir, 'operations.ts'), `${header('(no spec yet)')}\nexport const apiPrefix = '/api/v0'\n`)
    continue
  }
  try {
    const rel = relative(resolve(root, '..'), spec)
    const doc = parse(readFileSync(spec, 'utf8'))
    const ast = await openapiTS(pathToFileURL(spec))
    writeFileSync(join(outDir, 'schema.ts'), header(rel) + astToString(ast))
    const prefix = serverPrefix(doc)
    writeFileSync(join(outDir, 'operations.ts'), `${header(rel)}
export const apiPrefix = ${JSON.stringify(prefix)}
`)
    console.log(`[gen:api] ${app.key}: ${rel} -> prefix "${prefix}"`)
  }
  catch (err) {
    failed = true
    console.error(`[gen:api] ${app.key}: failed for ${spec}:`, err.message)
  }
}
process.exit(failed ? 1 : 0)
